/* eslint-disable @next/next/no-img-element -- the brush is a CSS-cropped region of the logo file, which next/image cannot express */
"use client";
import { useEffect, useRef, useState } from "react";
import { ArrowUpRight, Volume2, VolumeX } from "lucide-react";

const TOTAL_MS = 8200; // keep in sync with the timeline in app/intro.css
const SPLATTER = [[-62, -30, 9], [-30, -64, 6], [8, -78, 11], [44, -56, 7], [72, -14, 10], [66, 34, 6], [30, 62, 9], [-12, 72, 7], [-52, 48, 11], [-78, 8, 6], [92, -48, 5], [-96, -40, 5]] as const;
const VOICE_SRC = "/intro-voice.mp3"; // generated by scripts/generate-intro-voice.mjs
const WORDS_A = ["Software.", "AI.", "Automation."];

/** Full-screen intro: slide 1 "Introducing" + logo build, slide 2 positioning line, then a curtain reveal. Plays once per browser session. */
export function IntroSplash() {
  const [gone, setGone] = useState(false);
  const [skip, setSkip] = useState(false);
  const [run, setRun] = useState(0); // bumping this remounts the intro so it restarts in sync with the voice
  const [hasVoice, setHasVoice] = useState(false);
  const [blocked, setBlocked] = useState(false);
  const [muted, setMuted] = useState(false);
  const audio = useRef<HTMLAudioElement | null>(null);

  // voice: try to start with the intro; browsers may block unmuted autoplay, in which case offer a tap-for-sound
  useEffect(() => {
    if (!document.documentElement.classList.contains("intro-active")) return;
    const a = new Audio(VOICE_SRC);
    a.preload = "auto";
    audio.current = a;
    const ready = () => setHasVoice(true);
    a.addEventListener("canplaythrough", ready, { once: true });
    const t = setTimeout(() => {
      a.play().then(() => setBlocked(false)).catch((err: unknown) => {
        if ((err as { name?: string })?.name === "NotAllowedError") { setHasVoice(true); setBlocked(true); }
      });
    }, 150);
    return () => { clearTimeout(t); a.pause(); a.removeEventListener("canplaythrough", ready); audio.current = null; };
  }, [run]);
  useEffect(() => { if (audio.current) audio.current.muted = muted; }, [muted, run]);
  useEffect(() => { if (skip) audio.current?.pause(); }, [skip]);

  useEffect(() => {
    const root = document.documentElement;
    if (!root.classList.contains("intro-active")) { queueMicrotask(() => setGone(true)); return; }
    if (!skip) { try { history.scrollRestoration = "manual"; } catch {} scrollTo(0, 0); }
    const finish = () => {
      root.classList.remove("intro-active");
      try { sessionStorage.setItem("sparkv-intro", "1"); } catch {}
      queueMicrotask(() => setGone(true));
    };
    const t = setTimeout(finish, skip ? 650 : TOTAL_MS);
    const key = (e: KeyboardEvent) => { if (e.key === "Escape" || e.key === "Enter") setSkip(true); };
    addEventListener("keydown", key);
    return () => { clearTimeout(t); removeEventListener("keydown", key); };
  }, [skip, run]);

  if (gone) return null;
  return (
    <div key={run} className={`intro ${skip ? "is-skip" : ""}`} role="dialog" aria-label="SparkV introduction" aria-live="off">
      <div className="intro-panel l" /><div className="intro-panel r" />
      <div className="intro-glow" aria-hidden="true" />

      <section className="intro-slide s1">
        <p className="intro-kicker"><span>INTRODUCING</span></p>
        <div className="intro-logo">
          <img className="il-letters" src="/sparkv-logo.webp" alt="SparkV" width={2000} height={524} />
          <div className="il-brush"><img src="/sparkv-logo.webp" alt="" aria-hidden="true" width={2000} height={524} /></div>
          <i className="il-ring" />
          <div className="il-splat" aria-hidden="true">{SPLATTER.map(([x, y, s], i) => <b key={i} style={{ "--x": `${x}px`, "--y": `${y}px`, "--s": `${s}px`, "--d": `${2.55 + (i % 4) * 0.04}s` } as React.CSSProperties} />)}</div>
        </div>
      </section>

      <section className="intro-slide s2" aria-hidden="true">
        <h2 className="is2-title">{WORDS_A.map((w, i) => <span key={w} style={{ "--i": i } as React.CSSProperties}><em>{w}</em></span>)}</h2>
        <p className="is2-sub">Built for what’s next.</p>
        <div className="is2-stroke"><img src="/sparkv-logo.webp" alt="" width={2000} height={524} /></div>
      </section>

      <div className="intro-hud" aria-hidden="true">
        <span className="ih-bar"><i className="b1" /></span><span className="ih-bar"><i className="b2" /></span>
        <small>SPARKV</small>
      </div>
      <div className="intro-tools">
        {hasVoice && !blocked && <button className="intro-sound" onClick={() => setMuted((m) => !m)} aria-label={muted ? "Unmute intro voice" : "Mute intro voice"}>{muted ? <VolumeX size={15} /> : <Volume2 size={15} />}</button>}
        <button className="intro-skip" onClick={() => setSkip(true)}>Skip intro <ArrowUpRight size={14} /></button>
      </div>
      {blocked && <button className="intro-tap" onClick={() => { setBlocked(false); setRun((r) => r + 1); }}><Volume2 size={15} /> Tap for sound</button>}
    </div>
  );
}
